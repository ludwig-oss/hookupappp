export function habitsForFaults(faults: FaultId[]): WellnessHabit[] {
  const set = new Set(faults);
  const scored = WELLNESS_HABITS.map((h) => ({
    h,
    n: h.targets.filter((t) => set.has(t)).length,
  }));
  scored.sort((a, b) => b.n - a.n || a.h.step - b.h.step);
  const picked = scored.filter((s) => s.n > 0).map((s) => s.h);
  const rest = WELLNESS_HABITS.filter((h) => !picked.some((p) => p.id === h.id));
  return [...picked, ...rest].slice(0, 50);
}
